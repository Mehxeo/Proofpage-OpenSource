"""Documentation drafts for a frozen dataset: an EU AI Act training-content summary contribution,
a Hugging Face dataset card, and Croissant metadata.

These are drafting aids built only from what Proofpage recorded. They are not legal advice, and a model
provider's public summary covers all of its training data, not one dataset. Output is deterministic for a
frozen dataset so bundles stay reproducible.
"""
import json
import math
import urllib.parse

from .core import USER_AGENT
from .quality import findings
from .rights import BASES, revision_rights

DISCLAIMER = 'Draft generated by Proofpage from recorded evidence. Not legal advice. Review and complete it before publishing.'
FAMILY_NAMES = {
    'ai_crawler': 'robots.txt rules naming AI crawlers', 'content_usage': 'IETF Content-Usage (draft) in robots.txt or HTTP headers',
    'content_signal': 'Cloudflare Content-Signal in robots.txt', 'tdmrep': 'TDMRep (HTTP headers, HTML meta, /.well-known/tdmrep.json)',
    'noai': 'noai in X-Robots-Tag or meta robots', 'rsl': 'RSL License directives in robots.txt', 'license': 'Published licenses (link, meta, JSON-LD)',
}
ORIGINS = {'manual': 'Written by a reviewer', 'external_agent': 'Drafted by a connected agent', 'source_branch': 'Taken from a supplied conversation branch'}


def _size_category(count):
    for limit, label in ((1000, 'n<1K'), (10000, '1K<n<10K'), (100000, '10K<n<100K'), (1000000, '100K<n<1M')):
        if count < limit:
            return label
    return 'n>1M'


def build(store, dataset_id):
    rows = store.rows('SELECT d.id,d.name,d.created_at,d.hash,d.revision_ids,m.format,m.manifest FROM datasets d LEFT JOIN dataset_manifests m ON m.dataset_id=d.id WHERE d.id=?', (dataset_id,))
    if not rows:
        raise ValueError('Dataset not found.')
    dataset = rows[0]
    revision_ids = json.loads(dataset['revision_ids'])
    marks = ','.join('?' * len(revision_ids))
    revisions = store.rows(f'SELECT r.id,r.text,r.metadata,r.captured_at,s.kind source_kind,s.location,s.name source_name FROM revisions r JOIN items i ON i.id=r.item_id JOIN sources s ON s.id=i.source_id WHERE r.id IN ({marks}) ORDER BY r.id', revision_ids) if revision_ids else []
    snapshot = {row['revision_id']: row for row in store.rows('SELECT revision_id,verdict,basis,drifted FROM dataset_rights WHERE dataset_id=?', (dataset_id,))}
    manifest = json.loads(dataset['manifest']) if dataset['manifest'] else None

    domains, imports, families, screening = {}, {}, {}, {}
    characters, web_times = 0, []
    for revision in revisions:
        size = len(revision['text'].encode('utf-8'))
        characters += len(revision['text'])
        for finding in findings(revision['text']):
            screening[finding['code']] = screening.get(finding['code'], 0) + 1
        if revision['source_kind'] == 'web':
            url = json.loads(revision['metadata'] or '{}').get('url') or revision['location']
            host = (urllib.parse.urlsplit(url).hostname or 'unknown').lower()
            entry = domains.setdefault(host, {'domain': host, 'bytes': 0, 'records': 0})
            entry['bytes'] += size
            entry['records'] += 1
            web_times.append(revision['captured_at'])
            at_capture = revision_rights(store, revision['id']).get('at_capture')
            for family in sorted({signal['family'] for signal in (at_capture or {}).get('signals', [])}):
                families[family] = families.get(family, 0) + 1
        else:
            entry = imports.setdefault(revision['source_name'], {'source': revision['source_name'], 'records': 0, 'bytes': 0})
            entry['records'] += 1
            entry['bytes'] += size

    ranked = sorted(domains.values(), key=lambda d: (-d['bytes'], d['domain']))
    top = ranked[:max(1, math.ceil(len(ranked) * 0.10))] if ranked else []
    total_web = sum(d['bytes'] for d in ranked) or 1
    verdicts, bases = {}, {}
    for row in snapshot.values():
        verdicts[row['verdict']] = verdicts.get(row['verdict'], 0) + 1
        if row['basis']:
            bases[row['basis']] = bases.get(row['basis'], 0) + 1
    origins = {}
    for record in (manifest or {}).get('records', []):
        origin = record.get('origin', 'unknown')
        key = 'model' if origin.startswith('model:') else origin
        origins[key] = origins.get(key, 0) + 1

    summary = {
        'schema': 'proofpage.training-content-summary.v1', 'disclaimer': DISCLAIMER,
        'general': {'dataset': dataset['name'], 'dataset_id': dataset['id'], 'sha256': dataset['hash'], 'frozen_at': dataset['created_at'],
                    'format': ('training examples: ' + dataset['format']) if dataset['format'] else 'text corpus (JSONL)',
                    'modality': 'text', 'records': len((manifest or {}).get('records', [])) or len(revisions), 'source_revisions': len(revisions), 'characters': characters},
        'sources': {
            'publicly_available_datasets': [],
            'supplied_archives': sorted(imports.values(), key=lambda e: e['source']),
            'crawled': {
                'crawler': USER_AGENT, 'purpose': 'User-directed, bounded collection of individual public pages; no bulk crawling.',
                'period': {'from': min(web_times), 'to': max(web_times)} if web_times else None,
                'content_types': ['web pages (HTML or plain text)'] if domains else [],
                'domain_count': len(ranked),
                'top_domains_by_size': [{**d, 'share': round(d['bytes'] / total_web, 4)} for d in top],
                'top_domains_rule': 'Top 10% of domains by bytes of text collected (at least one). SMEs may disclose the top 5% or 1,000 domains, whichever is lower.',
            },
            'synthetic': {'model_drafted_examples': origins.get('model', 0)},
            'example_origins': {ORIGINS.get(key, 'Drafted by a model' if key == 'model' else key): count for key, count in sorted(origins.items())},
        },
        'rights': {
            'collection_behaviour': ['Respects robots.txt for its own user agent, including crawl-delay and request-rate.', 'Never bypasses logins, paywalls, or CAPTCHAs.',
                                     'Applies per-host cooldowns (at least 30 seconds) and a daily budget of 100 requests per host.'],
            'signals_recorded': [FAMILY_NAMES[f] for f in FAMILY_NAMES],
            'records_by_signal_found': {FAMILY_NAMES[f]: n for f, n in sorted(families.items())},
            'verdicts_at_freeze': dict(sorted(verdicts.items())),
            'reserved_included_with_basis': {BASES.get(b, b): n for b, n in sorted(bases.items())},
            'policy': 'Pages whose publisher reserved AI training are excluded unless a reviewer recorded a rights basis. If a source reserves AI training after freezing, downloads are blocked until a basis is recorded. Unknown means no machine-readable signal was found; it is not treated as permission, and each record still required explicit reviewer permission.',
            'not_read': 'Terms-of-service text, ai.txt, and signals published only off-page are not read.',
        },
        'illegal_content': {'assessed': False, 'note': 'Proofpage does not assess legality. Heuristic credential and personal-data screening ran on every revision.',
                            'screening_findings_by_type': dict(sorted(screening.items()))},
    }
    return {'summary': summary, 'summary_markdown': summary_markdown(summary), 'dataset_card': dataset_card(summary), 'croissant': croissant(summary)}


def summary_markdown(s):
    g, crawled, rights = s['general'], s['sources']['crawled'], s['rights']
    lines = [f"# Training-content summary — {g['dataset']}", '', f"> {s['disclaimer']} A provider's public summary covers all training data; merge this dataset's contribution into it.", '',
             '## 1. General information', '',
             f"- **Dataset:** {g['dataset']} (`{g['dataset_id']}`)", f"- **SHA-256:** `{g['sha256']}`", f"- **Frozen:** {g['frozen_at']}",
             f"- **Modality:** {g['modality']} · **Format:** {g['format']}", f"- **Size:** {g['records']} records from {g['source_revisions']} source revisions, {g['characters']:,} characters", '',
             '## 2. List of data sources', '', '### 2.1 Publicly available datasets', '', 'None recorded by Proofpage.', '',
             '### 2.2 Supplied archives and private data', '']
    lines += [f"- {e['source']}: {e['records']} records" for e in s['sources']['supplied_archives']] or ['None.']
    lines += ['', '### 2.3 Data crawled from online sources', '']
    if crawled['domain_count']:
        period = crawled['period']
        lines += [f"- **Crawler:** `{crawled['crawler']}` — {crawled['purpose']}", f"- **Collection period:** {period['from']} to {period['to']}",
                  f"- **Content:** {', '.join(crawled['content_types'])}", f"- **Domains:** {crawled['domain_count']}. {crawled['top_domains_rule']}", '',
                  '| Domain | Records | Bytes | Share |', '| --- | --- | --- | --- |']
        lines += [f"| {d['domain']} | {d['records']} | {d['bytes']:,} | {d['share']:.1%} |" for d in crawled['top_domains_by_size']]
    else:
        lines.append('None.')
    lines += ['', '### 2.4 Synthetic data', '', f"{s['sources']['synthetic']['model_drafted_examples']} examples were drafted by a model and approved by a reviewer."]
    if s['sources']['example_origins']:
        lines += [''] + [f'- {name}: {count}' for name, count in s['sources']['example_origins'].items()]
    lines += ['', '## 3. Data processing', '', '### 3.1 Respecting reservations of rights', '']
    lines += [f'- {item}' for item in rights['collection_behaviour']]
    lines += ['- Signals recorded at every capture: ' + '; '.join(rights['signals_recorded']) + '.', f"- {rights['policy']}", f"- Not read: {rights['not_read']}", '',
              '| Verdict at freeze | Records |', '| --- | --- |']
    lines += [f'| {verdict} | {count} |' for verdict, count in rights['verdicts_at_freeze'].items()] or ['| none | 0 |']
    if rights['reserved_included_with_basis']:
        lines += ['', 'Included despite a reservation, with a recorded basis:'] + [f'- {basis}: {count}' for basis, count in rights['reserved_included_with_basis'].items()]
    lines += ['', '### 3.2 Illegal content', '', s['illegal_content']['note']]
    lines += [f'- {code}: {count} revisions' for code, count in s['illegal_content']['screening_findings_by_type'].items()] or ['- No screening findings.']
    return '\n'.join(lines) + '\n'


def dataset_card(s):
    g, crawled, rights = s['general'], s['sources']['crawled'], s['rights']
    front = ['---', f"pretty_name: {json.dumps(g['dataset'])}", 'license: other', f"size_categories:\n- {_size_category(g['records'])}", 'tags:\n- proofpage\n- provenance', '---']
    body = [f"# {g['dataset']}", '', f"Frozen with Proofpage on {g['frozen_at']}. Every record traces to a captured source revision with its original evidence and capture time.", '',
            '## Dataset structure', '', f"- Format: {g['format']}", f"- Records: {g['records']} ({g['characters']:,} characters of source text)", f"- SHA-256: `{g['sha256']}`", '',
            '## Source data', '']
    if crawled['domain_count']:
        body += [f"- Web pages from {crawled['domain_count']} domains, collected {crawled['period']['from'][:10]} to {crawled['period']['to'][:10]} by `{crawled['crawler']}`."]
    body += [f"- Supplied archive: {e['source']} ({e['records']} records)" for e in s['sources']['supplied_archives']]
    body += ['', '## Rights and opt-outs', '', rights['policy'], '']
    body += [f'- {verdict}: {count}' for verdict, count in rights['verdicts_at_freeze'].items()]
    body += ['', 'The license is listed as `other` because records carry individual terms. See `rights.jsonl` and `RIGHTS.md` for each record.', '',
             '## Personal and sensitive information', '', s['illegal_content']['note'] + ' Screening is heuristic and not a complete privacy guarantee.', '',
             '## Limitations', '', '- Unknown rights mean no machine-readable signal was found, not that use is permitted.', '- Lexical capture of single pages; dynamic or attached content may be missing.',
             '', f"> {s['disclaimer']}"]
    return '\n'.join(front + [''] + body) + '\n'


